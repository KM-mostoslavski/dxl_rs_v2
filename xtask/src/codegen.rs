/// Module root, relative to `src/`.
pub const MODULE_FILE: &str = "models.rs";
/// Directory of the per-model files, relative to `src/`.
pub const MODULE_DIR: &str = "models";

/// First line of every generated file.
pub(crate) const HEADER: &str = "// @generated by `cargo xtask codegen`. Do not edit: change `control_tables/` and regenerate.\n";

/// One problem found in the input, naming the file it is in.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Diagnostic {
    /// The table's file stem, or `dynamixel` for the map.
    pub file: String,
    /// What is wrong.
    pub message: String,
}

impl Diagnostic {
    /// A diagnostic for `control_tables/<file>.ron`.
    pub(crate) fn new(file: impl Into<String>, message: impl Into<String>) -> Self {
        Self {
            file: file.into(),
            message: message.into(),
        }
    }
}

impl fmt::Display for Diagnostic {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "control_tables/{}.ron: {}", self.file, self.message)
    }
}

/// What a successful run did. Paths are relative to `src/`.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Report {
    /// Files written because their contents changed.
    pub written: Vec<PathBuf>,
    /// Stale model files removed.
    pub removed: Vec<PathBuf>,
    /// Files left as they were.
    pub unchanged: usize,
    /// Tables skipped because nothing maps them.
    pub warnings: Vec<Diagnostic>,
}

impl Report {
    /// The one stdout line of a successful run.
    pub fn summary(&self) -> String {
        format!(
            "generated {} files under src/ ({} written, {} removed, {} unchanged)",
            self.written.len() + self.unchanged,
            self.written.len(),
            self.removed.len(),
            self.unchanged
        )
    }
}

/// Why a run wrote nothing.
#[derive(Debug)]
pub enum Failure {
    /// The input failed one or more checks.
    Checks {
        /// Every problem, sorted by file then message.
        errors: Vec<Diagnostic>,
        /// Unmapped tables, as on success.
        warnings: Vec<Diagnostic>,
    },
    /// `rustfmt` is missing or failed on a generated file.
    Rustfmt(String),
    /// Writing the output failed.
    Io(String),
}

impl Failure {
    /// The stderr lines of a failed run: every `error:` line (sorted), then
    /// every `warning:` line.
    pub fn lines(&self) -> Vec<String> {
        match self {
            Self::Checks { errors, warnings } => errors
                .iter()
                .map(|e| format!("error: {e}"))
                .chain(warnings.iter().map(|w| format!("warning: {w}")))
                .collect(),
            Self::Rustfmt(message) | Self::Io(message) => vec![format!("error: {message}")],
        }
    }
}

/// Rendered files (path relative to `src/`, unformatted text), and the
/// warnings of a run whose checks passed.
#[derive(Debug)]
pub struct Generated {
    /// Every file to write.
    pub files: Vec<(String, String)>,
    /// Unmapped tables.
    pub warnings: Vec<Diagnostic>,
}

/// Reads `dynamixel.ron` and every table it references from `dir`, runs
/// every check, and renders the `models` files.
///
/// A broken map stops at once. A missing or unparsable table is one
/// diagnostic, and the other tables are still checked.
pub fn generate(dir: &Path) -> Result<Generated, Failure> {
    let checks = |errors| Failure::Checks {
        errors,
        warnings: Vec::new(),
    };
    let map = schema::parse_map(&dir.join("dynamixel.ron")).map_err(|d| checks(vec![d]))?;

    let mut errors = Vec::new();
    let mut tables = BTreeMap::new();
    let referenced: BTreeSet<&str> = map
        .models
        .values()
        .flat_map(|entry| entry.p1.iter().chain(entry.p2.iter()).flatten())
        .map(|table| table.file.as_str())
        .collect();
    for file in referenced {
        match schema::parse_table(&dir.join(format!("{file}.ron")), file) {
            Ok(table) => {
                tables.insert(file.to_string(), table);
            }
            Err(diagnostic) => errors.push(diagnostic),
        }
    }

    let on_disk = table_stems(dir).map_err(|d| checks(vec![d]))?;
    let outcome = resolve::resolve(&map, &tables, &on_disk);
    errors.extend(outcome.errors);
    if !errors.is_empty() {
        errors.sort();
        errors.dedup();
        return Err(Failure::Checks {
            errors,
            warnings: outcome.warnings,
        });
    }
    Ok(Generated {
        files: render::render(&outcome.resolved),
        warnings: outcome.warnings,
    })
}

/// The stems of `dir/*.ron`, except `dynamixel`.
fn table_stems(dir: &Path) -> Result<BTreeSet<String>, Diagnostic> {
    let unreadable = |e: std::io::Error| {
        Diagnostic::new("dynamixel", format!("cannot list {}: {e}", dir.display()))
    };
    let mut stems = BTreeSet::new();
    for entry in std::fs::read_dir(dir).map_err(unreadable)? {
        let path = entry.map_err(unreadable)?.path();
        if path.extension().is_some_and(|ext| ext == "ron")
            && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
            && stem != "dynamixel"
        {
            stems.insert(stem.to_string());
        }
    }
    Ok(stems)
}

/// Regenerates `src/models.rs` and `src/models/` under `root` from
/// `root/control_tables`. Nothing is written unless every step before the
/// write succeeded.
pub fn run(root: &Path) -> Result<Report, Failure> {
    run_with(root, output::format)
}

/// [`run`] with `format` in place of rustfmt.
fn run_with(
    root: &Path,
    format: impl Fn(&str, &str) -> Result<String, Failure>,
) -> Result<Report, Failure> {
    let generated = generate(&root.join("control_tables"))?;
    let mut formatted = Vec::with_capacity(generated.files.len());
    for (rel, text) in &generated.files {
        formatted.push((rel.clone(), format(rel, text)?));
    }
    let mut report = output::sync(&root.join("src"), &formatted)?;
    report.warnings = generated.warnings;
    Ok(report)
}

