//! Turns `control_tables/*.ron` into the `models` module: `src/models.rs`
//! plus one file per model in `src/models/`.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use serde::Deserialize;

/// Module root, relative to `src/`.
pub const MODULE_FILE: &str = "models.rs";
/// Directory of the per-model files, relative to `src/`.
pub const MODULE_DIR: &str = "models";

const HEADER: &str = "// @generated by `cargo xtask codegen`. Do not edit: change `control_tables/` and regenerate.\n";

/// `dynamixel.ron`: model number to model entry.
#[derive(Debug, Deserialize)]
pub struct ModelMap {
    pub models: BTreeMap<u16, ModelEntry>,
}

/// One model number in `dynamixel.ron`.
#[derive(Debug, Deserialize)]
pub struct ModelEntry {
    pub family: String,
    pub name: String,
    pub tables: Vec<TableRef>,
}

/// A control table file and the first firmware version it applies to.
#[derive(Debug, Deserialize)]
pub struct TableRef {
    pub from_fw: u8,
    pub file: String,
}

/// The part of a model's `.ron` file codegen reads; other fields are ignored.
#[derive(Debug, Deserialize)]
pub struct ControlTable {
    pub control_table: Vec<RegisterEntry>,
}

/// One row of a control table.
#[derive(Debug, Deserialize)]
pub struct RegisterEntry {
    pub address: u16,
    pub size: u8,
    pub data_name: String,
}

/// Generated files (path relative to `src/`, contents), plus the
/// table files no model number points to.
#[derive(Debug)]
pub struct Output {
    pub files: Vec<(String, String)>,
    pub unmapped: Vec<String>,
}

/// A table resolved against its model entry, ready to render.
struct Model<'a> {
    number: u16,
    entry: &'a ModelEntry,
    table_ref: &'a TableRef,
    /// Firmware version where the next table takes over, if any.
    until_fw: Option<u8>,
    table: ControlTable,
}

/// Reads `dynamixel.ron` and every table it references from `dir`, and
/// renders the `models` module files.
pub fn generate(dir: &Path) -> Result<Output, String> {
    let map: ModelMap = parse(&dir.join("dynamixel.ron"))?;
    let mut models = Vec::new();
    for (&number, entry) in &map.models {
        validate_tables(number, entry)?;
        for (i, table_ref) in entry.tables.iter().enumerate() {
            let table = parse_table(&dir.join(format!("{}.ron", table_ref.file)))?;
            models.push(Model {
                number,
                entry,
                table_ref,
                until_fw: entry.tables.get(i + 1).map(|next| next.from_fw),
                table,
            });
        }
    }

    let mut files = Vec::with_capacity(models.len() + 1);
    let mut type_names = BTreeSet::new();
    for model in &models {
        let ty = type_ident(&model.table_ref.file);
        if !type_names.insert(ty.clone()) {
            return Err(format!("two tables generate the type `{ty}`"));
        }
        files.push((
            format!("{MODULE_DIR}/{}.rs", module_ident(&model.table_ref.file)),
            render_model(model)?,
        ));
    }
    files.push((MODULE_FILE.to_string(), render_module(&map, &models)));

    Ok(Output {
        files,
        unmapped: unmapped_tables(dir, &map)?,
    })
}

fn parse<T: for<'de> Deserialize<'de>>(path: &Path) -> Result<T, String> {
    parse_with(path, |text| text.to_string())
}

/// Parses a control table, whose records are written with braces; see
/// [`braces_to_parens`].
fn parse_table(path: &Path) -> Result<ControlTable, String> {
    parse_with(path, braces_to_parens)
}

fn parse_with<T: for<'de> Deserialize<'de>>(
    path: &Path,
    prepare: fn(&str) -> String,
) -> Result<T, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    ron::from_str(&prepare(&text)).map_err(|e| format!("{}: {e}", path.display()))
}

/// Rewrites `{ key: value }` to `( key: value )`, leaving strings alone.
///
/// The control tables write records with braces, which RON reads as maps
/// whose bare keys turn into `()`, losing every field name. Parentheses make
/// them structs. Braces never mean a real map in a control table.
fn braces_to_parens(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut in_string = false;
    let mut escaped = false;
    for c in text.chars() {
        out.push(match c {
            _ if in_string && escaped => {
                escaped = false;
                c
            }
            '\\' if in_string => {
                escaped = true;
                c
            }
            '"' => {
                in_string = !in_string;
                c
            }
            '{' if !in_string => '(',
            '}' if !in_string => ')',
            _ => c,
        });
    }
    out
}

/// Tables must start at firmware 0 and be listed by strictly increasing
/// `from_fw`, so every firmware version maps to exactly one table.
fn validate_tables(number: u16, entry: &ModelEntry) -> Result<(), String> {
    match entry.tables.first() {
        None => return Err(format!("model {number}: no tables")),
        Some(first) if first.from_fw != 0 => {
            return Err(format!("model {number}: first table must have from_fw: 0"));
        }
        Some(_) => {}
    }
    if entry
        .tables
        .windows(2)
        .any(|w| w[0].from_fw >= w[1].from_fw)
    {
        return Err(format!("model {number}: from_fw must strictly increase"));
    }
    Ok(())
}

fn unmapped_tables(dir: &Path, map: &ModelMap) -> Result<Vec<String>, String> {
    let mapped: BTreeSet<&str> = map
        .models
        .values()
        .flat_map(|entry| entry.tables.iter().map(|t| t.file.as_str()))
        .collect();
    let mut unmapped = Vec::new();
    for dir_entry in std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let path = dir_entry.map_err(|e| e.to_string())?.path();
        if path.extension().is_some_and(|ext| ext == "ron") {
            let stem = path.file_stem().unwrap_or_default().to_string_lossy();
            if stem != "dynamixel" && !mapped.contains(stem.as_ref()) {
                unmapped.push(stem.into_owned());
            }
        }
    }
    unmapped.sort();
    Ok(unmapped)
}

/// `xm430_w350` -> `Xm430W350`. A leading digit is spelled out
/// (`2xl430_w250` -> `TwoXl430W250`) since identifiers can't start with one.
pub fn type_ident(file: &str) -> String {
    spell_leading_digit(file)
        .split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + chars.as_str()
            })
        })
        .collect()
}

/// `xm430_w350` -> `xm430_w350`, `2xl430_w250` -> `two_xl430_w250`.
pub fn module_ident(file: &str) -> String {
    spell_leading_digit(file)
}

fn spell_leading_digit(file: &str) -> String {
    const DIGITS: [&str; 10] = [
        "zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine",
    ];
    match file.chars().next().and_then(|c| c.to_digit(10)) {
        Some(d) => format!("{}_{}", DIGITS[d as usize], &file[1..]),
        None => file.to_string(),
    }
}

/// `Secondary(Shadow) ID` -> `SECONDARY_SHADOW_ID`.
pub fn const_ident(data_name: &str) -> String {
    data_name
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(str::to_ascii_uppercase)
        .collect::<Vec<_>>()
        .join("_")
}

fn firmware_doc(model: &Model) -> String {
    match (model.table_ref.from_fw, model.until_fw) {
        (0, None) => String::new(),
        (0, Some(until)) => format!(", firmware up to v{}", until - 1),
        (from, None) => format!(", firmware v{from} and later"),
        (from, Some(until)) => format!(", firmware v{from} to v{}", until - 1),
    }
}

fn render_model(model: &Model) -> Result<String, String> {
    let ty = type_ident(&model.table_ref.file);
    let mut out = String::from(HEADER);
    let _ = writeln!(
        out,
        "// Source: control_tables/{}.ron\n\nuse crate::{{Actuator, Id, register::Register}};\n",
        model.table_ref.file
    );
    let _ = writeln!(
        out,
        "/// {} (model number {}{}).\n#[derive(Debug, Clone, PartialEq, Eq)]\npub struct {ty} {{\n    id: Id,\n}}\n",
        model.entry.name,
        model.number,
        firmware_doc(model)
    );

    let _ = writeln!(
        out,
        "impl {ty} {{\n    pub(crate) const fn new(id: Id) -> Self {{\n        Self {{ id }}\n    }}\n"
    );
    let mut names = BTreeSet::new();
    for reg in &model.table.control_table {
        let name = const_ident(&reg.data_name);
        if !names.insert(name.clone()) {
            return Err(format!(
                "{}.ron: two registers named `{name}`",
                model.table_ref.file
            ));
        }
        let _ = writeln!(
            out,
            "    pub(crate) const {name}: Register = Register::new({}, {});",
            reg.address, reg.size
        );
    }
    out.push_str("}\n\n");

    let _ = writeln!(
        out,
        "impl Actuator for {ty} {{\n    fn id(&self) -> Id {{\n        self.id\n    }}\n\n    fn model_number(&self) -> u16 {{\n        {}\n    }}\n\n    fn name(&self) -> &'static str {{\n        {:?}\n    }}\n}}",
        model.number, model.entry.name
    );
    Ok(out)
}

fn render_module(map: &ModelMap, models: &[Model]) -> String {
    let mut out = String::from(HEADER);
    out.push_str(
        "//! Actuator model types, one per control table.\n\n\
         #![allow(\n    dead_code,\n    unused_variables,\n    reason = \"every register is generated but only some are wrapped; \
         feature-gated arms can leave parameters unused\"\n)]\n\n\
         use crate::{Actuator, Error, Id};\n\n",
    );

    for model in models {
        let module = module_ident(&model.table_ref.file);
        let ty = type_ident(&model.table_ref.file);
        let cfg = cfg_attr(&model.entry.family);
        let _ = writeln!(out, "{cfg}\nmod {module};\n{cfg}\npub use {module}::{ty};");
    }

    out.push_str(
        "\n/// Any supported actuator, one variant per model type.\n\
         ///\n\
         /// Match on it to reach a model's specific features; use the\n\
         /// [`Actuator`] trait for what every model has in common.\n\
         #[derive(Debug, Clone, PartialEq, Eq)]\n#[non_exhaustive]\npub enum ActuatorKind {\n",
    );
    for model in models {
        let ty = type_ident(&model.table_ref.file);
        let _ = writeln!(
            out,
            "    /// {}{}.\n    {}\n    {ty}({ty}),",
            model.entry.name,
            firmware_doc(model),
            cfg_attr(&model.entry.family)
        );
    }
    out.push_str("}\n\n");

    out.push_str(
        "impl ActuatorKind {\n\
         \x20   /// Builds the model type for `model_number`, picking the control table\n\
         \x20   /// that matches `firmware`.\n\
         \x20   ///\n\
         \x20   /// Fails with [`Error::UnsupportedModel`] if the model is unknown or its\n\
         \x20   /// family's Cargo feature is off.\n\
         \x20   pub(crate) fn new(model_number: u16, firmware: u8, id: Id) -> Result<Self, Error> {\n\
         \x20       match model_number {\n",
    );
    for (number, entry) in &map.models {
        let cfg = cfg_attr(&entry.family);
        for (i, table) in entry.tables.iter().enumerate() {
            let ty = type_ident(&table.file);
            let guard = entry.tables.get(i + 1).map_or_else(String::new, |next| {
                format!(" if firmware < {}", next.from_fw)
            });
            let _ = writeln!(
                out,
                "            {cfg}\n            {number}{guard} => Ok(Self::{ty}({ty}::new(id))),"
            );
        }
        let _ = writeln!(
            out,
            "            #[cfg(not(feature = \"{}\"))]\n            {number} => Err(Error::UnsupportedModel {{ model_number, feature: Some(\"{}\") }}),",
            entry.family, entry.family
        );
    }
    out.push_str(
        "            _ => Err(Error::UnsupportedModel { model_number, feature: None }),\n        }\n    }\n}\n\n",
    );

    out.push_str("impl Actuator for ActuatorKind {\n");
    for (method, ret) in [
        ("id", "Id"),
        ("model_number", "u16"),
        ("name", "&'static str"),
    ] {
        let _ = writeln!(
            out,
            "    fn {method}(&self) -> {ret} {{\n        match *self {{"
        );
        for model in models {
            let ty = type_ident(&model.table_ref.file);
            let _ = writeln!(
                out,
                "            {}\n            Self::{ty}(ref a) => a.{method}(),",
                cfg_attr(&model.entry.family)
            );
        }
        out.push_str("        }\n    }\n\n");
    }
    out.push_str("}\n");
    out
}

fn cfg_attr(family: &str) -> String {
    format!("#[cfg(feature = \"{family}\")]")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn type_names() {
        assert_eq!(type_ident("xm430_w350"), "Xm430W350");
        assert_eq!(type_ident("xl320"), "Xl320");
        assert_eq!(type_ident("2xl430_w250"), "TwoXl430W250");
        assert_eq!(type_ident("xl330_m077_fw52"), "Xl330M077Fw52");
    }

    #[test]
    fn module_names() {
        assert_eq!(module_ident("xm430_w350"), "xm430_w350");
        assert_eq!(module_ident("2xc430_w250"), "two_xc430_w250");
    }

    #[test]
    fn const_names() {
        assert_eq!(const_ident("Goal Position"), "GOAL_POSITION");
        assert_eq!(const_ident("Secondary(Shadow) ID"), "SECONDARY_SHADOW_ID");
        assert_eq!(const_ident("Baud Rate (Bus)"), "BAUD_RATE_BUS");
        assert_eq!(
            const_ident("In-Position Threshold"),
            "IN_POSITION_THRESHOLD"
        );
        assert_eq!(const_ident("Indirect Address 1"), "INDIRECT_ADDRESS_1");
    }

    fn entry(tables: &[(u8, &str)]) -> ModelEntry {
        ModelEntry {
            family: "x-series".into(),
            name: "XL330-M077".into(),
            tables: tables
                .iter()
                .map(|&(from_fw, file)| TableRef {
                    from_fw,
                    file: file.into(),
                })
                .collect(),
        }
    }

    #[test]
    fn braces_become_parens_outside_strings() {
        assert_eq!(
            braces_to_parens(r#"{ a: "{x}", b: "q\"}" }"#),
            r#"( a: "{x}", b: "q\"}" )"#
        );
    }

    #[test]
    fn table_order_is_validated() {
        assert!(validate_tables(1, &entry(&[(0, "a"), (53, "b")])).is_ok());
        assert!(validate_tables(1, &entry(&[])).is_err());
        assert!(validate_tables(1, &entry(&[(1, "a")])).is_err());
        assert!(validate_tables(1, &entry(&[(0, "a"), (0, "b")])).is_err());
        assert!(validate_tables(1, &entry(&[(0, "a"), (60, "b"), (53, "c")])).is_err());
    }

    fn fixture(map: &str, tables: &[(&str, &str)]) -> tempdir::Dir {
        let dir = tempdir::Dir::new();
        std::fs::write(dir.path().join("dynamixel.ron"), map).unwrap();
        for (name, body) in tables {
            std::fs::write(dir.path().join(format!("{name}.ron")), body).unwrap();
        }
        dir
    }

    const TABLE: &str = r#"(
        type_info: { value_of_zero_radian_position: 2048 },
        control_table: [
            (address: 0, size: 2, data_name: "Model Number"),
            (address: 116, size: 4, data_name: "Goal Position"),
        ],
    )"#;

    #[test]
    fn generates_model_and_dispatch() {
        let dir = fixture(
            r#"(models: { 1190: (family: "x-series", name: "XL330-M077", tables: [
                (from_fw: 0, file: "old"), (from_fw: 53, file: "new")]) })"#,
            &[("old", TABLE), ("new", TABLE), ("stray", TABLE)],
        );
        let out = generate(dir.path()).unwrap();
        assert_eq!(out.unmapped, ["stray"]);

        let file = |name: &str| &out.files.iter().find(|(n, _)| n == name).unwrap().1;
        let old = file("models/old.rs");
        assert!(old.starts_with(HEADER));
        assert!(old.contains("/// XL330-M077 (model number 1190, firmware up to v52)."));
        assert!(old.contains("pub(crate) const GOAL_POSITION: Register = Register::new(116, 4);"));
        assert!(old.contains("fn model_number(&self) -> u16 {\n        1190"));
        assert!(file("models/new.rs").contains("firmware v53 and later"));

        let module = file("models.rs");
        assert!(module.contains("1190 if firmware < 53 => Ok(Self::Old(Old::new(id))),"));
        assert!(module.contains("1190 => Ok(Self::New(New::new(id))),"));
        assert!(module.contains("feature: Some(\"x-series\")"));
        assert!(module.contains("Self::New(ref a) => a.name(),"));
    }

    #[test]
    fn rejects_duplicate_register_names() {
        let dup = r#"(control_table: [
            (address: 0, size: 2, data_name: "LED"),
            (address: 1, size: 1, data_name: "Led"),
        ])"#;
        let dir = fixture(
            r#"(models: { 1: (family: "ax", name: "A", tables: [(from_fw: 0, file: "a")]) })"#,
            &[("a", dup)],
        );
        let err = generate(dir.path()).unwrap_err();
        assert!(err.contains("two registers named `LED`"), "{err}");
    }

    #[test]
    fn rejects_duplicate_type_names() {
        let dir = fixture(
            r#"(models: {
                1: (family: "ax", name: "A", tables: [(from_fw: 0, file: "a")]),
                2: (family: "ax", name: "B", tables: [(from_fw: 0, file: "a")]),
            })"#,
            &[("a", TABLE)],
        );
        assert!(generate(dir.path()).unwrap_err().contains("type `A`"));
    }

    #[test]
    fn reports_missing_files() {
        let dir = fixture(
            r#"(models: { 1: (family: "ax", name: "A", tables: [(from_fw: 0, file: "gone")]) })"#,
            &[],
        );
        assert!(generate(dir.path()).unwrap_err().contains("gone.ron"));
    }

    /// Minimal self-cleaning temp directory, to avoid a dependency for tests.
    mod tempdir {
        use std::path::{Path, PathBuf};
        use std::sync::atomic::{AtomicU32, Ordering};

        pub struct Dir(PathBuf);

        impl Dir {
            pub fn new() -> Self {
                static NEXT: AtomicU32 = AtomicU32::new(0);
                let path = std::env::temp_dir().join(format!(
                    "xtask-codegen-{}-{}",
                    std::process::id(),
                    NEXT.fetch_add(1, Ordering::Relaxed)
                ));
                std::fs::create_dir_all(&path).unwrap();
                Self(path)
            }

            pub fn path(&self) -> &Path {
                &self.0
            }
        }

        impl Drop for Dir {
            fn drop(&mut self) {
                let _ = std::fs::remove_dir_all(&self.0);
            }
        }
    }
}
