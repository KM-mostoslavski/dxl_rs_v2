//! Turns `control_tables/*.ron` into the `models` module: `src/models.rs`,
//! one file per table in `src/models/`, and the generated tests.
//!
//! Everything is parsed, checked, rendered and formatted in memory first;
//! only then are changed files written (validate, then write).

#[cfg(test)]
mod fixtures;
mod names;
mod output;
mod render;
mod render_tests;
mod resolve;
mod schema;

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::path::{Path, PathBuf};

/// Module root, relative to `src/`.
pub const MODULE_FILE: &str = "models.rs";
/// Directory of the per-model files, relative to `src/`.
pub const MODULE_DIR: &str = "models";

/// First line of every generated file.
pub(crate) const HEADER: &str = "// @generated by `cargo xtask codegen`. Do not edit: change `control_tables/` and regenerate.\n";

/// One problem found in the input, naming the file it is in.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Diagnostic {
    /// The table's file stem, or `dynamixel` for the map.
    pub file: String,
    /// What is wrong.
    pub message: String,
}

impl Diagnostic {
    /// A diagnostic for `control_tables/<file>.ron`.
    pub(crate) fn new(file: impl Into<String>, message: impl Into<String>) -> Self {
        Self {
            file: file.into(),
            message: message.into(),
        }
    }
}

impl fmt::Display for Diagnostic {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "control_tables/{}.ron: {}", self.file, self.message)
    }
}

/// What a successful run did. Paths are relative to `src/`.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Report {
    /// Files written because their contents changed.
    pub written: Vec<PathBuf>,
    /// Stale model files removed.
    pub removed: Vec<PathBuf>,
    /// Files left as they were.
    pub unchanged: usize,
    /// Tables skipped because nothing maps them.
    pub warnings: Vec<Diagnostic>,
}

impl Report {
    /// The one stdout line of a successful run.
    pub fn summary(&self) -> String {
        format!(
            "generated {} files under src/ ({} written, {} removed, {} unchanged)",
            self.written.len() + self.unchanged,
            self.written.len(),
            self.removed.len(),
            self.unchanged
        )
    }
}

/// Why a run wrote nothing.
#[derive(Debug)]
pub enum Failure {
    /// The input failed one or more checks.
    Checks {
        /// Every problem, sorted by file then message.
        errors: Vec<Diagnostic>,
        /// Unmapped tables, as on success.
        warnings: Vec<Diagnostic>,
    },
    /// `rustfmt` is missing or failed on a generated file.
    Rustfmt(String),
    /// Writing the output failed.
    Io(String),
}

impl Failure {
    /// The stderr lines of a failed run: every `error:` line (sorted), then
    /// every `warning:` line.
    pub fn lines(&self) -> Vec<String> {
        match self {
            Self::Checks { errors, warnings } => errors
                .iter()
                .map(|e| format!("error: {e}"))
                .chain(warnings.iter().map(|w| format!("warning: {w}")))
                .collect(),
            Self::Rustfmt(message) | Self::Io(message) => vec![format!("error: {message}")],
        }
    }
}

/// Rendered files (path relative to `src/`, unformatted text), and the
/// warnings of a run whose checks passed.
#[derive(Debug)]
pub struct Generated {
    /// Every file to write.
    pub files: Vec<(String, String)>,
    /// Unmapped tables.
    pub warnings: Vec<Diagnostic>,
}

/// Reads `dynamixel.ron` and every table it references from `dir`, runs
/// every check, and renders the `models` files.
///
/// A broken map stops at once. A missing or unparsable table is one
/// diagnostic, and the other tables are still checked.
pub fn generate(dir: &Path) -> Result<Generated, Failure> {
    let checks = |errors| Failure::Checks {
        errors,
        warnings: Vec::new(),
    };
    let map = schema::parse_map(&dir.join("dynamixel.ron")).map_err(|d| checks(vec![d]))?;

    let mut errors = Vec::new();
    let mut tables = BTreeMap::new();
    let referenced: BTreeSet<&str> = map
        .models
        .values()
        .flat_map(|entry| entry.p1.iter().chain(entry.p2.iter()).flatten())
        .map(|table| table.file.as_str())
        .collect();
    for file in referenced {
        match schema::parse_table(&dir.join(format!("{file}.ron")), file) {
            Ok(table) => {
                tables.insert(file.to_string(), table);
            }
            Err(diagnostic) => errors.push(diagnostic),
        }
    }

    let on_disk = table_stems(dir).map_err(|d| checks(vec![d]))?;
    let outcome = resolve::resolve(&map, &tables, &on_disk);
    errors.extend(outcome.errors);
    if !errors.is_empty() {
        errors.sort();
        errors.dedup();
        return Err(Failure::Checks {
            errors,
            warnings: outcome.warnings,
        });
    }
    Ok(Generated {
        files: render::render(&outcome.resolved),
        warnings: outcome.warnings,
    })
}

/// The stems of `dir/*.ron`, except `dynamixel`.
fn table_stems(dir: &Path) -> Result<BTreeSet<String>, Diagnostic> {
    let unreadable = |e: std::io::Error| {
        Diagnostic::new("dynamixel", format!("cannot list {}: {e}", dir.display()))
    };
    let mut stems = BTreeSet::new();
    for entry in std::fs::read_dir(dir).map_err(unreadable)? {
        let path = entry.map_err(unreadable)?.path();
        if path.extension().is_some_and(|ext| ext == "ron")
            && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
            && stem != "dynamixel"
        {
            stems.insert(stem.to_string());
        }
    }
    Ok(stems)
}

/// Regenerates `src/models.rs` and `src/models/` under `root` from
/// `root/control_tables`. Nothing is written unless every step before the
/// write succeeded.
pub fn run(root: &Path) -> Result<Report, Failure> {
    run_with(root, output::format)
}

/// [`run`] with `format` in place of rustfmt.
fn run_with(
    root: &Path,
    format: impl Fn(&str, &str) -> Result<String, Failure>,
) -> Result<Report, Failure> {
    let generated = generate(&root.join("control_tables"))?;
    let mut formatted = Vec::with_capacity(generated.files.len());
    for (rel, text) in &generated.files {
        formatted.push((rel.clone(), format(rel, text)?));
    }
    let mut report = output::sync(&root.join("src"), &formatted)?;
    report.warnings = generated.warnings;
    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;
    use fixtures::{Map, Root, Table, xm_map};

    #[test]
    fn diagnostic_display() {
        let d = Diagnostic::new("xm430_w350", "missing role Goal Position");
        assert_eq!(
            d.to_string(),
            "control_tables/xm430_w350.ron: missing role Goal Position"
        );
    }

    #[test]
    fn diagnostics_sort_by_file_then_message() {
        let mut ds = vec![
            Diagnostic::new("b", "a"),
            Diagnostic::new("a", "z"),
            Diagnostic::new("a", "b"),
        ];
        ds.sort();
        assert_eq!(
            ds,
            [
                Diagnostic::new("a", "b"),
                Diagnostic::new("a", "z"),
                Diagnostic::new("b", "a"),
            ]
        );
    }

    fn file<'a>(files: &'a [(String, String)], name: &str) -> &'a str {
        &files.iter().find(|(n, _)| n == name).unwrap().1
    }

    fn checks(result: Result<Generated, Failure>) -> Vec<Diagnostic> {
        match result {
            Err(Failure::Checks { errors, .. }) => errors,
            other => panic!("expected check failures, got {other:?}"),
        }
    }

    #[test]
    fn generates_model_and_dispatch() {
        let root = Root::new(
            &Map::new()
                .model(1190, "x-series", "XL330-M077")
                .p2(&[(0, "old"), (53, "new")]),
            &[
                ("old", Table::xm().protocols("[P2]")),
                ("new", Table::xm().protocols("[P2]")),
                ("stray", Table::xm()),
            ],
        );
        let out = generate(&root.control_tables()).unwrap();
        assert_eq!(out.warnings.len(), 1);
        assert_eq!(out.warnings[0].file, "stray");

        let old = file(&out.files, "models/old.rs");
        assert!(old.starts_with(HEADER));
        assert!(old.contains("XL330-M077 (model number 1190"));
        assert!(file(&out.files, "models/new.rs").contains("firmware v53 and later"));

        let module = file(&out.files, "models.rs");
        assert!(module.contains("if firmware < 53 => Ok(Self::Old(Old::new(id))),"));
        assert!(module.contains("=> Ok(Self::New(New::new(id))),"));
        assert!(module.contains("feature: Some(\"x-series\")"));
    }

    #[test]
    fn rejects_duplicate_register_names() {
        let root = Root::new(
            &xm_map(),
            &[(
                "xm",
                Table::xm()
                    .with_row(200, 1, "LED", "RW", "RAM")
                    .with_row(201, 1, "Led", "RW", "RAM"),
            )],
        );
        let errors = checks(generate(&root.control_tables()));
        assert!(
            errors
                .iter()
                .any(|d| d.file == "xm" && d.message.contains("LED") && d.message.contains("Led")),
            "{errors:?}"
        );
    }

    #[test]
    fn rejects_duplicate_type_names() {
        let root = Root::new(
            &Map::new()
                .model(1, "ax", "A")
                .p1(&[(0, "xl_320")])
                .model(2, "ax", "B")
                .p1(&[(0, "xl320")]),
            &[("xl_320", Table::ax()), ("xl320", Table::ax())],
        );
        let errors = checks(generate(&root.control_tables()));
        assert!(
            errors
                .iter()
                .any(|d| d.message.contains("Xl320") && d.message.contains("xl_320")),
            "{errors:?}"
        );
    }

    #[test]
    fn reports_missing_files() {
        let root = Root::new(&Map::new().model(1, "ax", "A").p1(&[(0, "gone")]), &[]);
        let errors = checks(generate(&root.control_tables()));
        assert!(errors.iter().any(|d| d.file == "gone"), "{errors:?}");
    }

    /// The real `control_tables/`, resolved and rendered, with an
    /// independent row lookup per table.
    struct Real {
        map: schema::ModelMap,
        tables: BTreeMap<String, schema::ControlTable>,
        resolved: resolve::Resolved,
        files: Vec<(String, String)>,
    }

    fn real() -> Real {
        let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap()
            .join("control_tables");
        let map = schema::parse_map(&dir.join("dynamixel.ron")).unwrap();
        let tables: BTreeMap<String, schema::ControlTable> = mapped_files(&map)
            .into_iter()
            .map(|f| {
                let table = schema::parse_table(&dir.join(format!("{f}.ron")), &f).unwrap();
                (f, table)
            })
            .collect();
        let outcome = resolve::resolve(&map, &tables, &table_stems(&dir).unwrap());
        assert!(outcome.errors.is_empty(), "{:?}", outcome.errors);
        let files = render::render(&outcome.resolved);
        Real {
            map,
            tables,
            resolved: outcome.resolved,
            files,
        }
    }

    fn mapped_files(map: &schema::ModelMap) -> BTreeSet<String> {
        map.models
            .values()
            .flat_map(|e| e.p1.iter().chain(e.p2.iter()).flatten())
            .map(|t| t.file.clone())
            .collect()
    }

    fn compact(text: &str) -> String {
        text.split_whitespace().collect()
    }

    fn find<'a>(table: &'a schema::ControlTable, name: &str) -> Option<&'a schema::Row> {
        table.control_table.iter().find(|r| r.data_name == name)
    }

    fn reg_line(row: &schema::Row) -> String {
        format!(
            "pub(crate) const {}: Register = super::reg({}, {}, Access::{:?}, Area::{:?});",
            names::const_ident(&row.data_name),
            row.address,
            row.size,
            row.access,
            row.area
        )
    }

    impl Real {
        fn model(&self, file: &str) -> &resolve::GenModel {
            self.resolved
                .models
                .iter()
                .find(|m| m.file == file)
                .unwrap_or_else(|| panic!("no model {file}"))
        }

        fn text(&self, stem: &str) -> &str {
            let module = &self.model(stem).module_ident;
            file(&self.files, &format!("models/{module}.rs"))
        }
    }

    #[test]
    fn real_tables_roles_match_oracle() {
        use resolve::{Limits, ModeRole};
        let real = real();
        let mut checked = 0;
        for model in &real.resolved.models {
            let table = &real.tables[&model.file];
            let row = |name| find(table, name);
            let text = real.text(&model.file);
            let c = compact(text);
            let roles = &model.roles;
            for (name, resolved) in [
                ("Model Number", &roles.model_number),
                ("Firmware Version", &roles.firmware_version),
                ("Torque Enable", &roles.torque_enable),
                ("Goal Position", &roles.goal_position),
                ("Present Position", &roles.present_position),
            ] {
                let oracle = row(name).unwrap_or_else(|| panic!("{}: no {name}", model.file));
                assert_eq!(resolved, oracle, "{}: {name}", model.file);
                assert!(text.contains(&reg_line(oracle)), "{}: {name}", model.file);
            }
            let limits = match (
                row("Min Position Limit"),
                row("Max Position Limit"),
                row("CW Angle Limit"),
                row("CCW Angle Limit"),
            ) {
                (Some(min), Some(max), None, None) => {
                    assert!(c.contains("limits:LimitRegisters::MinMax{min:Self::MIN_POSITION_LIMIT,max:Self::MAX_POSITION_LIMIT}"));
                    Limits::MinMax {
                        min: min.clone(),
                        max: max.clone(),
                    }
                }
                (None, None, Some(cw), Some(ccw)) => {
                    assert!(c.contains("limits:LimitRegisters::CwCcw{cw:Self::CW_ANGLE_LIMIT,ccw:Self::CCW_ANGLE_LIMIT}"));
                    Limits::CwCcw {
                        cw: cw.clone(),
                        ccw: ccw.clone(),
                    }
                }
                other => panic!("{}: limits {other:?}", model.file),
            };
            assert_eq!(roles.limits, limits, "{}", model.file);
            match row("Hardware Error Status") {
                Some(oracle) => {
                    assert_eq!(roles.hardware_error.as_ref(), Some(oracle));
                    assert!(c.contains("hardware_error:Some(Self::HARDWARE_ERROR_STATUS)"));
                }
                None => {
                    assert_eq!(roles.hardware_error, None);
                    assert!(c.contains("hardware_error:None"), "{}", model.file);
                }
            }
            let mode_row = row("Operating Mode")
                .map(|r| (r, "OPERATING_MODE"))
                .or_else(|| row("Control Mode").map(|r| (r, "CONTROL_MODE")));
            match (mode_row, &table.operating_modes) {
                (Some((oracle, constant)), Some(values)) => {
                    assert_eq!(
                        roles.mode,
                        ModeRole::Register {
                            row: oracle.clone(),
                            values: values.clone()
                        }
                    );
                    assert!(text.contains(&reg_line(oracle)));
                    let expected = compact(&format!(
                        "mode:ModeSource::Register{{register:Self::{constant},values:ModeValues{{bounded:&{:?},unbounded:&{:?},no_position:&{:?}}}}}",
                        values.bounded, values.unbounded, values.no_position
                    ));
                    assert!(c.contains(&expected), "{}: {expected}", model.file);
                }
                (None, None) => {
                    assert_eq!(roles.mode, ModeRole::AngleLimits);
                    assert!(c.contains("mode:ModeSource::AngleLimits"), "{}", model.file);
                }
                other => panic!("{}: mode {other:?}", model.file),
            }
            let t = &table.type_info;
            let scale = compact(&format!(
                "scale:PositionScale::new({},{},{},{:?},{:?})",
                t.value_of_zero_radian_position,
                t.value_of_min_radian_position,
                t.value_of_max_radian_position,
                t.min_radian,
                t.max_radian
            ));
            assert!(c.contains(&scale), "{}: {scale}", model.file);
            checked += 1;
        }
        assert_eq!(checked, mapped_files(&real.map).len());
        assert_eq!(checked, real.tables.len());

        let xm = real.text("xm430_w350");
        assert!(xm.contains(
            "pub(crate) const GOAL_POSITION: Register = super::reg(116, 4, Access::RW, Area::Ram);"
        ));
        assert!(xm.contains(
            "pub(crate) const OPERATING_MODE: Register = super::reg(11, 1, Access::RW, Area::Eeprom);"
        ));
        assert!(compact(xm).contains("mode:ModeSource::Register{register:Self::OPERATING_MODE,"));

        let ax = real.model("ax_12a");
        let Limits::CwCcw { cw, ccw } = &ax.roles.limits else {
            panic!("AX-12A: expected CW/CCW limits");
        };
        assert_eq!((cw.address, ccw.address), (6, 8));
        assert_eq!(ax.roles.hardware_error, None);
        assert_eq!(ax.roles.mode, ModeRole::AngleLimits);

        let xl320 = real.model("xl320");
        assert!(
            matches!(&xl320.roles.limits, Limits::CwCcw { cw, ccw } if (cw.address, ccw.address) == (6, 8))
        );
        assert_eq!(
            xl320.roles.hardware_error.as_ref().map(|r| r.address),
            Some(50)
        );
        assert!(
            matches!(&xl320.roles.mode, ModeRole::Register { row, .. } if row.data_name == "Control Mode" && row.address == 11)
        );

        let ph = real.model("ph54_200_s500");
        assert_eq!(ph.roles.goal_position.address, 564);
        assert_eq!(
            ph.roles.hardware_error.as_ref().map(|r| r.address),
            Some(518)
        );
        assert!(matches!(&ph.roles.mode, ModeRole::Register { row, .. } if row.address == 11));

        let ym = real.model("ym070_210_m001");
        assert!(find(&real.tables["ym070_210_m001"], "Error Code").is_some());
        assert_eq!(ym.roles.hardware_error, None);
        assert!(
            matches!(&ym.roles.mode, ModeRole::Register { row, .. } if row.data_name == "Operating Mode" && row.address == 33)
        );
    }
}
